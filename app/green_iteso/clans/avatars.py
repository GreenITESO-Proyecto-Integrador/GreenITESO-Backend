"""Private storage for clan avatars (#164).

The leader uploads the image as the multipart field ``avatar``. Keys are
generated by ``core.image_storage`` as ``clan-avatars/<clan_id>/<uuid>.<ext>``,
so a stored key always points at an image this app validated and wrote for
that clan.
"""

from __future__ import annotations

from uuid import UUID

from django.core.files.uploadedfile import UploadedFile

from green_iteso.core.image_storage import (
    MAX_IMAGE_BYTES,
    InvalidImageError,
    delete_image,
    save_image,
)

CLAN_AVATAR_PREFIX = "clan-avatars"
MAX_CLAN_AVATAR_BYTES = MAX_IMAGE_BYTES
InvalidClanAvatarError = InvalidImageError


def save_clan_avatar(clan_id: UUID, uploaded: UploadedFile) -> str:
    """Validate and store ``uploaded``; return the new private object key."""
    return save_image(CLAN_AVATAR_PREFIX, clan_id, uploaded)


def delete_clan_avatar(clan_id: UUID, object_key: str) -> None:
    """Best-effort removal of a stored clan avatar; other keys are left untouched."""
    delete_image(CLAN_AVATAR_PREFIX, clan_id, object_key)
